// Runs after `next build`: writes out/manifest.webmanifest and out/sw.js.
// The service worker precaches every file of the build, so after the first visit the app works offline.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const base = process.env.PAGES_BASE_PATH ?? "";

// Manifest colors come from the light "card" theme tokens: no second copy of the palette.
const css = readFileSync(join(root, "src/styles/themes/card.css"), "utf8");
const token = (name) => {
  const m = css.match(new RegExp(`--${name}:\\s*([^;]+);`));
  if (!m) throw new Error(`token --${name} not found in card.css`);
  return m[1].trim();
};

const manifest = {
  name: "Спорт трекер",
  short_name: "Спорт трекер",
  description: "Личный дневник тренировок и замеров. Данные хранятся только на телефоне.",
  lang: "ru",
  id: `${base}/`,
  start_url: `${base}/`,
  scope: `${base}/`,
  display: "standalone",
  orientation: "portrait",
  background_color: token("bg"),
  theme_color: token("bg"),
  icons: [
    { src: `${base}/icons/icon-192.png`, sizes: "192x192", type: "image/png", purpose: "any" },
    { src: `${base}/icons/icon-512.png`, sizes: "512x512", type: "image/png", purpose: "any" },
    { src: `${base}/icons/icon-512.png`, sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
};
writeFileSync(join(outDir, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, files);
    else files.push(p);
  }
  return files;
}

// URL for each file; a page "a/index.html" is requested as "a/" (trailingSlash).
const SKIP = new Set(["sw.js", ".nojekyll"]);
const hash = createHash("sha256");
const urls = [];
for (const file of walk(outDir).sort()) {
  const rel = relative(outDir, file).replaceAll("\\", "/");
  if (SKIP.has(rel)) continue;
  hash.update(rel).update(readFileSync(file));
  urls.push(`${base}/${rel.endsWith("index.html") ? rel.slice(0, -"index.html".length) : rel}`);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-pwa.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const CACHE = "st-" + VERSION;
const FILES = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

// A new version waits until the app restarts (the page asks for SKIP_WAITING at startup), then drops old caches.
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith("st-") && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
  if (event.data === "VERSION") event.source?.postMessage({ version: VERSION });
});

// Cache first: the whole app is in the cache, the network is only a fallback for anything missed.
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(request, { ignoreSearch: true });
    if (hit) return hit;
    try {
      return await fetch(request);
    } catch (err) {
      if (request.mode === "navigate") {
        const page = (await cache.match(BASE + "/404.html")) || (await cache.match(BASE + "/"));
        if (page) return page;
      }
      throw err;
    }
  })());
});
`;
writeFileSync(join(outDir, "sw.js"), sw);

const size = urls.reduce((sum, u) => sum + statSync(join(outDir, u.slice(base.length + 1).replace(/\/$|^$/, (m) => (m ? "/index.html" : "index.html")))).size, 0);
console.log(`PWA: manifest + sw.js (version ${version}), precache ${urls.length} files, ${(size / 1024).toFixed(0)} KB`);
