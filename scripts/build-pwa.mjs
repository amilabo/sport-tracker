// Runs after `next build`: writes out/manifest.webmanifest and out/sw.js.
// The service worker precaches every file of the build, so after the first visit the app works offline.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const base = process.env.PAGES_BASE_PATH ?? "";

// Manifest colors come from the light "card" theme tokens: no second copy of the palette.
const css = readFileSync(join(root, "src/styles/themes/card.css"), "utf8");
const token = (name) => {
  const m = css.match(new RegExp(`--${name}:\\s*([^;]+);`));
  if (!m) throw new Error(`token --${name} not found in card.css`);
  return m[1].trim();
};

const manifest = {
  name: "Спорт трекер",
  short_name: "Спорт трекер",
  description: "Личный дневник тренировок и замеров. Данные хранятся только на телефоне.",
  lang: "ru",
  id: `${base}/`,
  start_url: `${base}/`,
  scope: `${base}/`,
  display: "standalone",
  orientation: "portrait",
  background_color: token("bg"),
  theme_color: token("bg"),
  icons: [
    { src: `${base}/icons/icon-192.png`, sizes: "192x192", type: "image/png", purpose: "any" },
    { src: `${base}/icons/icon-512.png`, sizes: "512x512", type: "image/png", purpose: "any" },
    { src: `${base}/icons/icon-512.png`, sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
};
writeFileSync(join(outDir, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, files);
    else files.push(p);
  }
  return files;
}

// URL for each file; a page "a/index.html" is requested as "a/" (trailingSlash).
const SKIP = new Set(["sw.js", ".nojekyll"]);
const hash = createHash("sha256");
const urls = [];
for (const file of walk(outDir).sort()) {
  const rel = relative(outDir, file).replaceAll("\\", "/");
  if (SKIP.has(rel)) continue;
  hash.update(rel).update(readFileSync(file));
  urls.push(`${base}/${rel.endsWith("index.html") ? rel.slice(0, -"index.html".length) : rel}`);
}
const version = hash.digest("hex").slice(0, 12);

// A page of the build must refer only to scripts, styles and fonts of the same build. The service worker checks
// this on install (see below); here the same check guards the build itself, so it can never reject a good deploy.
const STATIC_REF = /\/_next\/static\/[^"'\\\s)]+/g;
const isPage = (url) => url.endsWith("/") || url.endsWith(".html");
const staticFiles = new Set(urls.filter((u) => u.includes("/_next/static/")).map((u) => u.slice(u.indexOf("/_next/static/"))));
for (const url of urls.filter(isPage)) {
  const file = join(outDir, url.slice(base.length + 1) + (url.endsWith("/") ? "index.html" : ""));
  const missing = (readFileSync(file, "utf8").match(STATIC_REF) ?? []).filter((ref) => !staticFiles.has(ref));
  if (missing.length) throw new Error(`build-pwa: ${url} refers to files outside the build: ${missing.slice(0, 3).join(", ")}`);
}

const sw = `// Generated by scripts/build-pwa.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const CACHE = "st-" + VERSION;
const FILES = ${JSON.stringify(urls)};
const STATIC_REF = ${STATIC_REF};

// Every file straight from the network ("reload"): GitHub Pages lets the browser keep a page for 10 minutes,
// and an old page in the new cache points to scripts that are gone after a deploy — a white screen.
// A page from another build (the CDN is still switching) fails the install; the next update check retries it.
self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    try {
      await cache.addAll(FILES.map((url) => new Request(url, { cache: "reload" })));
      const known = new Set(FILES.filter((u) => u.includes("/_next/static/")).map((u) => u.slice(u.indexOf("/_next/static/"))));
      for (const url of FILES.filter((u) => u.endsWith("/") || u.endsWith(".html"))) {
        const page = await (await cache.match(url)).text();
        const stray = (page.match(STATIC_REF) || []).find((ref) => !known.has(ref));
        if (stray) throw new Error("page " + url + " is from another build: " + stray);
      }
    } catch (err) {
      await caches.delete(CACHE);
      throw err;
    }
  })());
});

// A new version waits until the app restarts (the page asks for SKIP_WAITING at startup).
// The previous version's cache is kept until the next update: a page still open from it may load its scripts.
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const older = (await caches.keys()).filter((key) => key.startsWith("st-") && key !== CACHE);
    for (const key of older.slice(0, -1)) await caches.delete(key);
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
  if (event.data === "VERSION") event.source?.postMessage({ version: VERSION });
});

// Cache first: the whole app is in the cache, the network is only a fallback for anything missed.
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + "/")) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // This version first, then the kept previous one (a page opened before the switch).
    const hit = (await cache.match(request, { ignoreSearch: true })) || (await caches.match(request, { ignoreSearch: true }));
    if (hit) return hit;
    try {
      return await fetch(request);
    } catch (err) {
      if (request.mode === "navigate") {
        const page = (await cache.match(BASE + "/404.html")) || (await cache.match(BASE + "/"));
        if (page) return page;
      }
      throw err;
    }
  })());
});
`;
writeFileSync(join(outDir, "sw.js"), sw);

const size = urls.reduce((sum, u) => sum + statSync(join(outDir, u.slice(base.length + 1).replace(/\/$|^$/, (m) => (m ? "/index.html" : "index.html")))).size, 0);
console.log(`PWA: manifest + sw.js (version ${version}), precache ${urls.length} files, ${(size / 1024).toFixed(0)} KB`);
